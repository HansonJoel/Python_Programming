'''
The Range function is used to loop through a set of code.
'''

# Print range of value from o to 6
for i in range(6):
    print(i)  # the output stops at 5

# We can also specify the starting and ending value by adding the parameter
for i in range(2,6):  # where 2 is the starting value and 6 is the end value
    print(i)


# We can also increment the value
for i in range(2,30,3):
    print(i)
